#!/usr/bin/env python3
"""Emit the pinned random-provider ranges used by the body-execution probe.

This is a partial decoder, not a totality or service-contract claim. Missing
callees and unsupported instructions remain failing fetches. Cached and
initialized refill paths are included; this is not a total kernel decoder.
"""
import argparse
import hashlib
import json
import re

from census import ORACLE, ROOT, extract


FUNCTIONS = {
    'get_random_u32', '__get_random_u32_raw', 'kcov_choice_ip',
    'check_kcov_mode', 'kcov_choice_write', 'kcov_choice_write_area',
    'kcov_steer_find', '__sanitizer_cov_trace_cmp8',
    '__sanitizer_cov_trace_const_cmp8',
    '_get_random_bytes', 'crng_make_state', 'crng_fast_key_erasure',
    'chacha_block_generic', 'chacha_permute', '__memcpy', 'memcpy_orig',
}


def generated():
    expected = '06513d05fc37506b6cea546e8f11b9fe328e482265341ca41c242157bfa5e88e'
    if hashlib.sha256(ORACLE.read_bytes()).hexdigest() != expected:
        raise ValueError('wrong oracle image')
    functions = [f for f in extract(ORACLE, FUNCTIONS) if f['name'] in FUNCTIONS]
    if {f['name'] for f in functions} != FUNCTIONS:
        raise ValueError('a requested random-service range is missing')
    text = ['import Image', 'namespace Binary.RandomImage',
            '-- Generated by generate_random_service.py from the pinned ELF.',
            '-- Partial ranges: unsupported instructions and absent callees fail closed.',
            'def listing : List (Nat × Nat × String) := [']
    rows = []
    for function in functions:
        for row in function['instructions']:
            raw = bytes.fromhex(row['bytes'])
            if branch := re.fullmatch(r'(j\w+|call) L_([0-9a-f]+)', row['normalized']):
                target = int(branch[2], 16)
                width = 1 if len(raw) == 2 else 4
                actual = (row['pc'] + len(raw) + int.from_bytes(raw[-width:], 'little', signed=True)) % 2**64
                if actual != target:
                    raise ValueError(f'branch encoding differs at {row["pc"]:x}')
            assembly = row['normalized']
            # This three-byte NOP has an encoded memory-shaped operand but
            # performs no memory access. Kraken already has sized NOPs.
            if raw == bytes.fromhex('0f1f00') and assembly == 'nopl   (%rax)':
                assembly = 'nop 3'
            rows.append((row['pc'], len(raw), assembly))
    text += ['  ' + ',\n  '.join(f'({pc}, {size}, {json.dumps(asm)})' for pc, size, asm in rows) + ']']
    text += ['def fetch (pc : Int64) : Option Decoded := do',
             '  let (_, size, assembly) ← listing.find? (fun row => row.1 == pc.toUInt64.toNat)',
             '  match Kraken.X64.Parser.parse assembly with',
             '  | .ok [.instr instruction] => some ⟨instruction, size⟩',
             '  | _ => none',
             'end Binary.RandomImage', '']
    return '\n'.join(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generated()
    path = ROOT / 'binary/RandomImage.lean'
    if args.check:
        if path.read_text() != text:
            raise ValueError('RandomImage.lean differs from the pinned ELF')
    else:
        path.write_text(text)
    print(f'RandomImage.lean: {"checked" if args.check else "generated"}')


if __name__ == '__main__':
    main()
