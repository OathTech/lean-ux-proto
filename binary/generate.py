#!/usr/bin/env python3
"""Emit this image's region terms and DWARF record predicates, not a checker."""
import hashlib
import re
from pathlib import Path
from elftools.elf.elffile import ELFFile

from census import ORACLE, ROOT, extract
from layouts import layouts


def main():
    expected = '16c346209885db6c610d4aa126c6eb30f5d3c02f0498d95e606473945f648774'
    if hashlib.sha256(ORACLE.read_bytes()).hexdigest() != expected:
        raise ValueError('wrong ELF')
    names = {'wg_index_hashtable_lookup': 'Lookup', 'wg_peer_get_maybe_zero': 'PeerGet'}
    text = ['import Kraken.X64.Parser', 'import Kraken.Layout', 'import Kraken.X64.Semantics',
            'import Execution',
            'open Kraken.X64.Parser', 'namespace Binary.Image',
            '-- Generated by binary/generate.py from the read-only oracle.']
    labels = {}
    region_names = []
    cut_addresses = []
    for f in extract(ORACLE):
        if f['name'] not in names:
            continue
        ns = names[f['name']]
        rows = f['instructions']
        starts = {f['entry']}
        for i in rows:
            pc, size, asm = i['pc'], len(bytes.fromhex(i['bytes'])), i['normalized']
            if m := re.match(r'(j\w+|call)\s+L_([0-9a-f]+)$', asm):
                target = int(m[2], 16)
                labels['L_' + m[2]] = target
                raw = bytes.fromhex(i['bytes'])
                width = 1 if len(raw) == 2 else 4
                if (pc + size + int.from_bytes(raw[-width:], 'little', signed=True)) % 2**64 != target:
                    raise ValueError(f'branch encoding disagrees at {pc:x}')
                starts.add(pc + size)
                if f['entry'] <= target < f['entry'] + f['size']:
                    starts.add(target)
            if asm == 'ret':
                starts.add(pc + size)
        cut_addresses.extend(sorted(starts & {i["pc"] for i in rows}))
        cut_addresses.extend(i["pc"] for i in rows
                             if i["normalized"].split()[0] in {"call", "cmp", "test", "ret"})
        blocks = []
        for i in rows:
            if i['pc'] in starts:
                blocks.append([])
            blocks[-1].append(i)
        text += [f'namespace {ns}', f'def entry : Int64 := .ofNat {f["entry"]}']
        for b in blocks:
            offset = b[0]['pc'] - f['entry']
            region_names.append((ns, offset))
            sizes = ', '.join(str(len(bytes.fromhex(i['bytes']))) for i in b)
            asm = '\n'.join(i['normalized'] for i in b)
            text += [f'-- +0x{offset:x}: {len(b)} instructions.',
                     f'def r{offset:02x} : List (Kraken.Sized Directive) :=',
                     f'  List.zipWith (fun d n => ⟨d, n⟩) (parse("{asm}")) [{sizes}]']
        text += ['def code : List (Kraken.Sized Directive) :=',
                 '  ' + ' ++ '.join(f'r{b[0]["pc"] - f["entry"]:02x}' for b in blocks),
                 f'end {ns}']
    text += [
        '/-- Anchored region entries, calls, compares/tests and returns; service internals are outside this cut domain. -/',
        'def cutPoints : List Int64 := [' + ", ".join(f".ofNat {pc}" for pc in sorted(set(cut_addresses))) + "]",
        '/-- Canonical labels also resolve in the ambient image, outside the anchored ranges. -/',
        'def canonicalAddress (name : String) : Option Int64 := do',
        "  let 'L' :: '_' :: digits := name.toList | none",
        '  if digits.length != 16 then return ← none',
        '  let n ← digits.foldlM (fun n c => do',
        "    let d ← if '0' ≤ c && c ≤ '9' then some (c.toNat - '0'.toNat)",
        "      else if 'a' ≤ c && c ≤ 'f' then some (c.toNat - 'a'.toNat + 10)",
        '      else none',
        '    return n * 16 + d) 0',
        '  return .ofNat n',
        'def linkedLabels : Labels := ⟨fun name => match name with']
    text += [f'  | "{name}" => .ofNat {pc}' for name, pc in sorted(labels.items())]
    # Unlisted labels must never occur in these terms. This is checked below
    # by the generated names and by strict PC dispatch at execution.
    text += ['  | _ => (canonicalAddress name).getD 0⟩',
             '/-- Exact lengths and addresses; absent PCs fail closed. -/',
             'def fetchIn (pc : Int64) (code : List (Kraken.Sized Directive))',
             '    (target : Int64) : Option Decoded :=',
             '  match code with',
             '  | [] => none',
             '  | ⟨d, n⟩ :: ds =>',
             '    if target = pc then match d with',
             '      | .instr i => some ⟨i, n⟩',
             '      | _ => none',
             '    else fetchIn (pc + .ofNat n) ds target',
             'def fetch (pc : Int64) : Option Decoded :=',
             '  (fetchIn Lookup.entry Lookup.code pc).orElse',
             '    (fun _ => fetchIn PeerGet.entry PeerGet.code pc)',
             'end Binary.Image', '']
    (ROOT / 'binary/Image.lean').write_text('\n'.join(text))
    proof = ['import Image', 'import RegionExecution',
             'set_option maxRecDepth 4096', 'set_option maxHeartbeats 2000000',
             'namespace Binary.Image', 'local instance : Labels := linkedLabels']
    for ns, offset in region_names:
        proof += [f'theorem {ns}_r{offset:02x}_layout :',
                  f'    LaidOut fetch ({ns}.entry + .ofNat {offset}) {ns}.r{offset:02x} := by',
                  '  repeat first',
                  '    | apply LaidOut.cons',
                  '    | exact LaidOut.nil _',
                  '    | apply regular_mono',
                  '    | exact True.intro',
                  '    | decide',
                  '    | rfl']
    proof += ['end Binary.Image', '']
    (ROOT / 'binary/ImageLayout.lean').write_text('\n'.join(proof))
    o = layouts(ORACLE)
    e, node, head = [o[n] for n in ('index_hashtable_entry', 'hlist_node', 'hlist_head')]
    text = ['import Kraken.Mem', 'import Leanux.WG.Types', 'namespace Binary.Layouts',
            '-- Generated DWARF offsets; physical pointer interpretation is separate.',
            f'def entrySize : Nat := {e["size"]}',
            f'def headSize : Nat := {head["size"]}']
    for name, offset in e['members'].items():
        text += [f'def entry_{name} : Nat := {offset}']
    text += [f'def node_next : Nat := {node["members"]["next"]}',
             f'def node_pprev : Nat := {node["members"]["pprev"]}',
             '/-- The three C scalar fields, represented by exact word equality. -/',
             'def EntryFields (m : Mem 64) (a peer : BitVec 64) (kind index : BitVec 32) : Prop :=',
             '  m.loadInt (a + .ofNat 64 entry_peer) 8 = some peer.toNat ∧',
             '  m.loadInt (a + .ofNat 64 entry_type) 4 = some kind.toNat ∧',
             '  m.loadInt (a + .ofNat 64 entry_index) 4 = some index.toNat',
             'end Binary.Layouts', '']
    # The landed keypair framing properties observe the lifetime identity,
    # global counter, and complete receiving-counter bitmap. Keep their
    # physical equations explicit even though lookup does not write them.
    text = text[:-2]
    for record, prefix in [('noise_keypair', 'keypair'),
                           ('noise_replay_counter', 'replay'),
                           ('noise_keypairs', 'slots'),
                           ('noise_symmetric_key', 'symmetric')]:
        row = o[record]
        text += [f'def {prefix}Size : Nat := {row["size"]}']
        text += [f'def {prefix}_{name} : Nat := {offset}'
                 for name, offset in row['members'].items()]
    peer_count = (o['wg_peer']['members']['refcount'] + o['kref']['members']['refcount']
                  + o['refcount_struct']['members']['refs'])
    text += [f'def peerSize : Nat := {o["wg_peer"]["size"]}',
             f'def peer_refcount : Nat := {peer_count}',
             f'def peer_keypairs : Nat := {o["wg_peer"]["members"]["keypairs"]}']
    with ORACLE.open('rb') as stream:
        symbols = ELFFile(stream).get_section_by_name('.symtab').get_symbol_by_name('keypair_counter')
        if not symbols or len(symbols) != 1 or symbols[0]['st_size'] != 8:
            raise ValueError('expected one eight-byte keypair_counter symbol')
        text += [f'def keypairCounterAddress : BitVec 64 := .ofNat 64 {symbols[0]["st_value"]}']
    bitmap = o['noise_replay_counter']['arrays']['backtrack']
    if bitmap != dict(count=128, element_size=8):
        raise ValueError(f'replay bitmap shape differs from mirror: {bitmap}')
    text += [
        f'def replayWords : Nat := {bitmap["count"]}',
        f'def replayWordBytes : Nat := {bitmap["element_size"]}',
        '/-- Exact physical replay counter and all 128 bitmap words. -/',
        'def ReplayFields (m : Mem 64) (a : BitVec 64) (r : Leanux.WG.ReplayCounter) : Prop :=',
        '  m.loadInt (a + .ofNat 64 replay_counter) 8 = some (r.counter : Int) ∧',
        '  r.backtrack.size = replayWords ∧',
        '  ∀ i (hi : i < r.backtrack.size),',
        '    m.loadInt (a + .ofNat 64 (replay_backtrack + i * replayWordBytes)) replayWordBytes = some (r.backtrack[i] : Int)',
        '/-- The fields read by the keypair-lifetime snapshot. Pointer/store',
        '    membership and the remaining keypair fields are separate obligations. -/',
        'def KeypairSnapshotFields (m : Mem 64) (a : BitVec 64) (k : Leanux.WG.Keypair) : Prop :=',
        '  m.loadInt (a + .ofNat 64 keypair_internal_id) 8 = some (k.internalId : Int) ∧',
        '  ReplayFields m (a + .ofNat 64 keypair_receiving_counter) k.receivingCounter',
        'def KeypairCounterField (m : Mem 64) (counter : Nat) : Prop :=',
        '  m.loadInt keypairCounterAddress 8 = some (counter : Int)',
        '/-- Key bytes, timestamp bit pattern and validity byte; no key placeholder is used here. -/',
        'def SymmetricFields (m : Mem 64) (a : BitVec 64) (k : Leanux.WG.SymmetricKey) : Prop :=',
        '  m.loadBytes (a + .ofNat 64 symmetric_key) 32 = some k.key ∧',
        '  m.loadInt (a + .ofNat 64 symmetric_birthdate) 8 = some k.birthdate.toBitVec.toNat ∧',
        '  m.loadInt (a + .ofNat 64 symmetric_is_valid) 1 = some (if k.isValid then 1 else 0)',
        '/-- All non-pointer mirror keypair fields. The entry peer word is',
        '    explicit: the owning-object and index-table views must agree on it. -/',
        'def KeypairFields (m : Mem 64) (a peerWord : BitVec 64) (k : Leanux.WG.Keypair) : Prop :=',
        '  KeypairSnapshotFields m a k ∧',
        '  SymmetricFields m (a + .ofNat 64 keypair_sending) k.sending ∧',
        '  SymmetricFields m (a + .ofNat 64 keypair_receiving) k.receiving ∧',
        '  m.loadInt (a + .ofNat 64 keypair_sending_counter) 8 = some (k.sendingCounter : Int) ∧',
        '  m.loadInt (a + .ofNat 64 keypair_remote_index) 4 = some (k.remoteIndex : Int) ∧',
        '  m.loadInt (a + .ofNat 64 keypair_i_am_the_initiator) 1 = some (if k.iAmTheInitiator then 1 else 0) ∧',
        '  m.loadInt (a + .ofNat 64 keypair_refcount) 4 = some (k.refcount : Int) ∧',
        '  m.loadInt (a + .ofNat 64 (keypair_entry + entry_peer)) 8 = some peerWord.toNat',
        'end Binary.Layouts', '']
    (ROOT / 'binary/Layouts.lean').write_text('\n'.join(text))


if __name__ == '__main__':
    main()
