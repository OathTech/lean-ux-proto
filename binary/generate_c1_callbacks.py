#!/usr/bin/env python3
"""Emit the literal terms of the two comparison callbacks the C1 statement
names that binary/generate.py does not cover: __sanitizer_cov_trace_cmp1 and
__sanitizer_cov_trace_cmp8 of the pinned s5 image. With --check, compare the
committed module with a fresh generation instead of writing it."""
import argparse
import json

from census import ORACLE, ROOT, extract
from target import verify_image

NAMES = ['__sanitizer_cov_trace_cmp1', '__sanitizer_cov_trace_cmp8']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    verify_image()
    functions = {f['name']: f for f in extract(ORACLE, NAMES)}
    rows = [i for name in NAMES for i in functions[name]['instructions']]
    text = '\n'.join([
        'import LiteralDecode',
        'namespace Binary.StatementC1CallbackImage',
        '-- Generated by binary/generate_c1_callbacks.py from the pinned ELF: __sanitizer_cov_trace_cmp1 and',
        '-- __sanitizer_cov_trace_cmp8. A parser rejection is a missing PC, never a no-op.',
        'def decoded : List (Nat × Nat × Option Instr) := [',
        '  ' + ',\n  '.join(f'({i["pc"]}, {len(bytes.fromhex(i["bytes"]))}, literalInstruction({json.dumps(i["normalized"])}))'
                            for i in rows) + ']',
        'def fetch (pc : Int64) : Option Decoded := do',
        '  let (_, size, code) ← decoded.find? (fun row => row.1 == pc.toUInt64.toNat)',
        '  match code with',
        '  | some instruction => some ⟨instruction, size⟩',
        '  | _ => none',
        'end Binary.StatementC1CallbackImage', ''])
    path = ROOT / 'binary/StatementC1CallbackImage.lean'
    if args.check:
        if path.read_text() != text:
            raise ValueError(f'{path.name} differs from the pinned image generation')
        print(f'{path.name}: checked')
    else:
        path.write_text(text)


if __name__ == '__main__':
    main()
