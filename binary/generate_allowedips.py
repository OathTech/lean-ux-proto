#!/usr/bin/env python3
"""Regenerate M2 literal regions and record offsets from the pinned ELF."""
import argparse
import hashlib
import json
import re
from census import ROOT, ORACLE, extract
from layouts import layouts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    def write(path, text):
        if args.check:
            if path.read_text() != text:
                raise ValueError(f'{path.name} differs from the pinned image generation')
            print(f'{path.name}: checked')
        else:
            path.write_text(text)
    if hashlib.sha256(ORACLE.read_bytes()).hexdigest() != "16c346209885db6c610d4aa126c6eb30f5d3c02f0498d95e606473945f648774":
        raise ValueError("wrong oracle image")
    functions = extract(ORACLE)
    text = ["import Image", "open Kraken.X64.Parser", "namespace Binary.AllowedipsImage",
            "-- Generated by binary/generate_allowedips.py; no instruction substitution."]
    allcuts = set()
    for name, ns in [("lookup", "Lookup"), ("common_bits", "CommonBits")]:
        matches = [f for f in functions if f['name'] == name and any(
            '/wireguard/allowedips.c:' in source for i in f['instructions'] for _, source in i['frames'])]
        if len(matches) != 1:
            raise ValueError(f"not one allowedips.c {name}: {len(matches)}")
        f, = matches
        rows = f['instructions']
        pcs = {i['pc'] for i in rows}
        starts = {f['entry']}
        for i in rows:
            pc, asm = i['pc'], i['normalized']
            raw = bytes.fromhex(i['bytes'])
            if branch := re.fullmatch(r'(j\w+|call) L_([0-9a-f]+)', asm):
                target = int(branch[2], 16)
                width = 1 if len(raw) == 2 else 4
                if (pc + len(raw) + int.from_bytes(raw[-width:], 'little', signed=True)) % 2**64 != target:
                    raise ValueError(f"branch encoding mismatch {pc:x}")
                starts.update([target, pc + len(raw)])
            if asm.startswith('ret'):
                starts.add(pc + len(raw))
            if asm.split()[0] in {'cmp','test','call','ret','cmovne'}:
                allcuts.add(pc)
                allcuts.add(pc + len(raw))
        starts &= pcs
        allcuts |= starts
        blocks = []
        for i in rows:
            if i['pc'] in starts:
                blocks.append([])
            blocks[-1].append(i)
        text += [f"namespace {ns}", f"def entry : Int64 := .ofNat {f['entry']}",
                 f"def byteSize : Nat := {f['size']}", f"def instructionCount : Nat := {len(rows)}"]
        regions = []
        for block in blocks:
            label = f"r{block[0]['pc']-f['entry']:02x}"
            regions.append(label)
            asm = '\n'.join(i['normalized'] for i in block)
            sizes = ', '.join(str(len(bytes.fromhex(i['bytes']))) for i in block)
            text += [f"def {label} : List (Kraken.Sized Directive) :=",
                     f'  List.zipWith (fun d n => ⟨d, n⟩) (parse("{asm}")) [{sizes}]']
        text += ["def code : List (Kraken.Sized Directive) := " + ' ++ '.join(regions), f"end {ns}"]
        print(f"{name}: {len(rows)} instructions, {len(blocks)} regions, {f['entry']:#x}")
    text += ['def cutPoints : List Int64 := [' + ', '.join(f'.ofNat {pc}' for pc in sorted(allcuts)) + ']',
             'def fetch (pc : Int64) : Option Decoded :=',
             '  (Image.fetchIn Lookup.entry Lookup.code pc).orElse',
             '    (fun _ => Image.fetchIn CommonBits.entry CommonBits.code pc)',
             'end Binary.AllowedipsImage', '']
    write(ROOT/'binary/AllowedipsImage.lean', '\n'.join(text))
    node = layouts(ORACLE)['allowedips_node']
    expected = dict(peer=8, bit=16, cidr=1, bit_at_a=1, bit_at_b=1, bitlen=1, bits=16)
    for field, size in expected.items():
        if node['member_sizes'][field] != size:
            raise ValueError(f"wrong DWARF field width {field}")
    text = ['import Memory', 'namespace Binary.AllowedipsLayout',
            '-- Generated DWARF record layout. Pointer structure lives in TrieHeap.',
            f"def nodeSize : Nat := {node['size']}"]
    text += [f"def {field} : Nat := {node['members'][field]}" for field in expected]
    text += ['def ScalarFields (m : Mem 64) (a : BitVec 64)',
             '    (cidrValue byteSelector bitSelector : Nat) : Prop :=',
             '  m.loadInt (a + .ofNat 64 cidr) 1 = some cidrValue ∧',
             '  m.loadInt (a + .ofNat 64 bit_at_a) 1 = some byteSelector ∧',
             '  m.loadInt (a + .ofNat 64 bit_at_b) 1 = some bitSelector',
             'end Binary.AllowedipsLayout', '']
    write(ROOT/'binary/AllowedipsLayout.lean', '\n'.join(text))


if __name__ == '__main__':
    main()
