#!/usr/bin/env python3
"""Generate the insertion image and mutation record fields from pinned s5."""
import argparse
import re

from census import extract
from generate_index_mutators import generate_group
from layouts import layouts
from target import ROOT, ORACLE, verify_image


ANCHORS = [('wg_allowedips_insert_v4', 'Insert4', 26),
           ('wg_allowedips_insert_v6', 'Insert6', 29), ('add.isra.0', 'Add', 506)]


def generated():
    verify_image()
    functions = extract(ORACLE, [name for name, _, _ in ANCHORS])
    files = generate_group(functions, 'AllowedipsMutation', ANCHORS, max_region_instructions=8)
    image = files['AllowedipsMutationImage.lean'].replace(
        'Generated by generate_index_mutators.py', 'Generated by generate_allowedips_mutation.py')
    # Fetch is balanced over instruction regions. Each leaf is still the literal
    # region, checked by its LaidOut theorem; large-prefix reduction is avoided.
    def fetch(namespace, body):
        regions = [(int(offset, 16), 'r'+offset) for offset in re.findall(r'^def r([0-9a-f]+) :', body, re.M)]
        def tree(xs, indent):
            if len(xs) == 1:
                offset, name = xs[0]
                return f'Image.fetchIn (entry + .ofNat {offset}) {name} pc'
            middle = len(xs)//2
            return (f'if pc < entry + .ofNat {xs[middle][0]} then\n{indent}  ' +
                    tree(xs[:middle], indent+'  ') + f'\n{indent}else\n{indent}  ' + tree(xs[middle:], indent+'  '))
        return body.replace('def fetch : Int64 → Option Decoded := Image.fetchIn entry code',
                            'def fetch (pc : Int64) : Option Decoded :=\n  '+tree(regions, '  '))
    for _, namespace, _ in ANCHORS:
        pattern = rf'(namespace {namespace}\n)(.*?)(end {namespace})'
        image = re.sub(pattern, lambda m: m[1]+fetch(namespace,m[2])+m[3], image, flags=re.S)
    files['AllowedipsMutationImage.lean'] = image
    files['AllowedipsMutationCodeLayout.lean'] = files.pop('AllowedipsMutationLayout.lean')
    records = layouts(ORACLE)
    fields = [('allowedips', 'root4', 8), ('allowedips', 'root6', 8), ('allowedips', 'seq', 8),
              ('allowedips_node', 'parent_bit_packed', 8), ('allowedips_node', 'peer_list', 16),
              ('wg_peer', 'allowedips_list', 16)]
    text = ['-- Generated from the pinned ELF DWARF; pointer interpretation is handwritten.',
            'namespace Binary.AllowedipsMutationLayout',
            f'def tableSize : Nat := {records["allowedips"]["size"]}']
    for record, field, width in fields:
        if records[record]['member_sizes'][field] != width:
            raise ValueError(f'{record}.{field}: wrong field width')
        text += [f'def {field} : Nat := {records[record]["members"][field]}']
    files['AllowedipsMutationLayout.lean'] = '\n'.join(text+['end Binary.AllowedipsMutationLayout', ''])
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in generated().items():
        path = ROOT/'binary'/name
        if args.check:
            if path.read_text() != text:
                raise ValueError(f'{name}: differs from pinned image/layout')
        else:
            path.write_text(text)
        print(f'{name}: {"checked" if args.check else "generated"}')


if __name__ == '__main__':
    main()
