#!/usr/bin/env python3
"""Generate the provider readiness layout from the pinned ELF's KCOV CU."""
import argparse
import hashlib
from elftools.elf.elffile import ELFFile
from census import ORACLE, ROOT

FIELDS = {
    'kcov': {'remote': 'objectRemote', 'steer': 'objectSteer'},
    'kcov_steer': {'n': 'steerCount', 'head': 'steerHead',
                   'mismatches': 'steerMismatches', 'e': 'steerEntries'},
    'kcov_steer_entry': {'len': 'entryLength'},
    'kcov_remote': {'handle': 'remoteHandle', 'kcov': 'remoteObject', 'hnode': 'remoteLink'},
    'task_struct': {'kcov': 'taskObject', 'kcov_handle': 'taskHandle'},
}
SIZES = {'kcov_steer_entry': 'entrySize'}
SYMBOLS = {'crng_is_ready': 'readyAddress', 'crng_init': 'initAddress',
           'batched_entropy_u32': 'cacheAddress', 'crngs': 'cpuAddress',
           'base_crng': 'baseAddress', 'kcov_choice_seq': 'sequenceAddress',
           'kcov_remote_map': 'remoteMapAddress'}


def generated():
    expected = '16c346209885db6c610d4aa126c6eb30f5d3c02f0498d95e606473945f648774'
    if hashlib.sha256(ORACLE.read_bytes()).hexdigest() != expected:
        raise ValueError('wrong oracle image')
    values = {}
    def add(name, value):
        if name in values and values[name] != value:
            raise ValueError(f'inconsistent layout: {name}')
        values[name] = value
    with ORACLE.open('rb') as stream:
        elf = ELFFile(stream)
        for symbol in elf.get_section_by_name('.symtab').iter_symbols():
            if symbol.name in SYMBOLS:
                add(SYMBOLS[symbol.name], symbol['st_value'])
        for cu in elf.get_dwarf_info().iter_CUs():
            name = cu.get_top_DIE().attributes.get('DW_AT_name')
            if not name or not name.value.decode().endswith('/kcov.c'):
                continue
            for die in cu.iter_DIEs():
                name = die.attributes.get('DW_AT_name')
                if die.tag != 'DW_TAG_structure_type' or not name or 'DW_AT_byte_size' not in die.attributes:
                    continue
                name = name.value.decode()
                if name not in FIELDS:
                    continue
                if name in SIZES:
                    add(SIZES[name], die.attributes['DW_AT_byte_size'].value)
                for member in die.iter_children():
                    field = member.attributes.get('DW_AT_name')
                    if member.tag != 'DW_TAG_member' or not field or field.value.decode() not in FIELDS[name]:
                        continue
                    offset = member.attributes['DW_AT_data_member_location'].value
                    if not isinstance(offset, int):
                        raise ValueError('nonconstant field offset')
                    add(FIELDS[name][field.value.decode()], offset)
    wanted = set(SIZES.values()) | set(SYMBOLS.values()) | {v for fields in FIELDS.values() for v in fields.values()}
    if values.keys() != wanted:
        raise ValueError(f'missing layout values: {wanted - values.keys()}')
    lines = ['-- Generated by generate_random_layout.py from the pinned ELF.',
             'namespace Binary.RandomProvider.Layout']
    lines += [f'def {name} : Nat := {values[name]}' for name in sorted(values)]
    return '\n'.join(lines + ['end Binary.RandomProvider.Layout', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generated()
    path = ROOT / 'binary/RandomLayout.lean'
    if args.check:
        if path.read_text() != text:
            raise ValueError('RandomLayout.lean differs from the pinned ELF')
    else:
        path.write_text(text)
    print(f'RandomLayout.lean: {"checked" if args.check else "generated"}')


if __name__ == '__main__':
    main()
