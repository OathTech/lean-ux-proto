"""This image's stable peer equations; pointer-shaped fields remain handwritten."""


def generate_peer_scalars(root, layouts):
    # Mirror field, C member, representation, required C width. The offsets
    # and member widths come from the pinned image's DWARF, not this table.
    records = [
        ('wg_peer', 0, [
            ('persistentKeepaliveInterval', 'persistent_keepalive_interval', 'nat', 2),
            ('isDead', 'is_dead', 'bool', 1),
            ('serialWorkCpu', 'serial_work_cpu', 'cpu', 4),
            ('internalId', 'internal_id', 'nat', 8),
            ('lastSentHandshake', 'last_sent_handshake', 'bits', 8),
            ('txBytes', 'tx_bytes', 'nat', 8),
            ('rxBytes', 'rx_bytes', 'nat', 8),
            ('walltimeLastHandshake', 'walltime_last_handshake', 'bytes', 16),
            ('timerHandshakeAttempts', 'timer_handshake_attempts', 'nat', 4),
            ('timerNeedAnotherKeepalive', 'timer_need_another_keepalive', 'bool', 1),
            ('sentLastminuteHandshake', 'sent_lastminute_handshake', 'bool', 1),
        ]),
        ('noise_handshake', layouts['wg_peer']['members']['handshake'], [
            ('remoteStatic', 'remote_static', 'bytes', 32),
            ('presharedKey', 'preshared_key', 'bytes', 32),
            ('precomputedStaticStatic', 'precomputed_static_static', 'bytes', 32),
            ('lastInitiationConsumption', 'last_initiation_consumption', 'bits', 8),
            ('handshakeState', 'state', 'nat', 4),
            ('latestTimestamp', 'latest_timestamp', 'bytes', 12),
            ('remoteIndex', 'remote_index', 'nat', 4),
            ('ephemeralPrivate', 'ephemeral_private', 'bytes', 32),
            ('remoteEphemeral', 'remote_ephemeral', 'bytes', 32),
            ('chainingKey', 'chaining_key', 'bytes', 32),
            ('hash', 'hash', 'bytes', 32),
        ]),
        ('cookie', layouts['wg_peer']['members']['latest_cookie'], [
            ('cookieMac1Key', 'message_mac1_key', 'bytes', 32),
            ('lastMac1Sent', 'last_mac1_sent', 'bytes', 16),
            ('haveSentMac1', 'have_sent_mac1', 'bool', 1),
            ('cookieDecryptionKey', 'cookie_decryption_key', 'bytes', 32),
            ('cookie', 'cookie', 'bytes', 16),
            ('cookieBirthdate', 'birthdate', 'bits', 8),
            ('cookieIsValid', 'is_valid', 'bool', 1),
        ]),
    ]
    fields = []
    for record, base, rows in records:
        for mirror, member, representation, size in rows:
            actual_size = layouts[record]['member_sizes'][member]
            if actual_size != size:
                raise ValueError(f'{record}.{member}: DWARF width {actual_size}, expected {size}')
            offset = base + layouts[record]['members'][member]
            if offset + size > layouts['wg_peer']['size']:
                raise ValueError(f'{record}.{member}: outside owning peer')
            fields.append((mirror, offset, size, representation))

    text = ['import Layouts', 'import Memory', 'set_option maxRecDepth 4096',
            'set_option maxHeartbeats 200000',
            'namespace Binary',
            '-- Generated by binary/generate.py from DWARF; field interpretation in peer_layouts.py.',
            '/-- Stable scalar and byte-array peer fields. This is one component,',
            '    not a complete peer relation: pointer structures, queues, timers,',
            '    refcount and the owning embedded entry have separate equations.',
            '    serialWorkCpu none denotes NR_CPUS = 1 in this image (cpumask.h).',
            '    No cryptographic field here is treated as an opaque placeholder. -/',
            'structure PeerStableFields (m : Mem 64) (a : BitVec 64) (p : Leanux.WG.Peer) : Prop where']
    equations = []
    for mirror, offset, size, representation in fields:
        address = f'(a + .ofNat 64 {offset})'
        if representation == 'bytes':
            equations.append(f'm.loadBytes {address} {size} = some p.{mirror}')
        else:
            value = {'nat': f'(p.{mirror} : Int)', 'bool': f'(if p.{mirror} then 1 else 0)',
                     'bits': f'(p.{mirror}.toBitVec.toNat : Int)',
                     'cpu': f'(p.{mirror}.getD 1 : Int)'}[representation]
            equations.append(f'm.loadInt {address} {size} = some {value}')
    text += ['\n'.join('  ' + mirror + ' : ' + equation for (mirror, _, _, _), equation in zip(fields, equations)), '',
             'def peerStableOffsets : List (Nat × Nat) :=',
             '  [' + ', '.join(f'({offset}, {size})' for _, offset, size, _ in fields) + ']', '',
             'def peerStableLocations (a : BitVec 64) : List (BitVec 64 × Nat) :=',
             '  peerStableOffsets.map (fun cell => (a + .ofNat 64 cell.1, cell.2))', '',
             '']
    for read in ['loadInt', 'loadBytes']:
        text += [f'private theorem stable_{read} {{before after : Mem 64}} {{writes : BitVec 64 → Prop}}',
                 '    (a : BitVec 64) (same : EqualOutside writes before after)',
                 '    (separate : ∀ location ∈ peerStableLocations a, ∀ i < location.2,',
                 '      ¬writes (location.1 + .ofNat 64 i))',
                 '    (off size : Nat) (member : (off, size) ∈ peerStableOffsets) :',
                 f'    before.{read} (a + .ofNat 64 off) size = after.{read} (a + .ofNat 64 off) size := by',
                 f'  apply EqualOutside.{read} same',
                 '  exact separate _ (List.mem_map_of_mem (f := fun cell : Nat × Nat =>',
                 '    (a + .ofNat 64 cell.1, cell.2)) member)', '']
    text += ['/-- Frame only the represented reads, permitting the separate',
             '    refcount and embedded-entry peer word to change. -/',
             'theorem PeerStableFields.frame {before after : Mem 64} {writes : BitVec 64 → Prop}',
             '    {a : BitVec 64} {p : Leanux.WG.Peer}',
             '    (same : EqualOutside writes before after)',
             '    (separate : ∀ location ∈ peerStableLocations a, ∀ i < location.2,',
             '      ¬writes (location.1 + .ofNat 64 i))',
             '    (represented : PeerStableFields before a p) : PeerStableFields after a p := by',
             '  refine { ' + ', '.join(mirror + ' := ?_' for mirror, _, _, _ in fields) + ' }']
    terms = []
    for i, (mirror, offset, size, representation) in enumerate(fields):
        read = 'loadBytes' if representation == 'bytes' else 'loadInt'
        terms.append(f'(stable_{read} a same separate {offset} {size} (by decide)).symm.trans represented.{mirror}')

    text += ['  · exact ' + term for term in terms]
    text += ['',
             'theorem PeerStableFields.refcount_update (m : Mem 64) (a : BitVec 64)',
             '    (p : Leanux.WG.Peer) (count : Nat) :',
             '    PeerStableFields m a {p with refcount := count} ↔ PeerStableFields m a p := by',
             '  constructor',
             '  · intro h; exact {' + ', '.join(mirror + ' := h.' + mirror for mirror, _, _, _ in fields) + '}',
             '  · intro h; exact {' + ', '.join(mirror + ' := h.' + mirror for mirror, _, _, _ in fields) + '}', '',
             '#print axioms PeerStableFields.frame', '#print axioms PeerStableFields.refcount_update', '']
    peer_count = (layouts['wg_peer']['members']['refcount']
                  + layouts['kref']['members']['refcount']
                  + layouts['refcount_struct']['members']['refs'])
    entry_peer = (layouts['wg_peer']['members']['handshake']
                  + layouts['noise_handshake']['members']['entry']
                  + layouts['index_hashtable_entry']['members']['peer'])
    text += [f'def peerHandshakePeerOffset : Nat := {entry_peer}',
             '/-- The mutable refcount and embedded handshake peer word are',
             '    disjoint from every represented stable field, by DWARF offsets. -/',
             'theorem peerStable_mutable_disjoint (a : BitVec 64) (location : BitVec 64 × Nat)',
             '    (present : location ∈ peerStableLocations a) (i : Nat) (hi : i < location.2) :',
             f'    ¬(InRange (a + .ofNat 64 {peer_count}) 4 (location.1 + .ofNat 64 i) ∨',
             f'      InRange (a + .ofNat 64 {entry_peer}) 8 (location.1 + .ofNat 64 i)) := by',
             '  obtain ⟨cell, member, rfl⟩ := List.mem_map.mp present',
             f'  let safe (p : Nat × Nat) : Prop := p.1+p.2 ≤ {layouts["wg_peer"]["size"]} ∧',
             f'    (p.1+p.2 ≤ {peer_count} ∨ {peer_count+4} ≤ p.1) ∧',
             f'    (p.1+p.2 ≤ {entry_peer} ∨ {entry_peer+8} ≤ p.1)',
             '  have checked : peerStableOffsets.all (fun p => decide (safe p)) = true := by decide',
             '  have facts : safe cell := of_decide_eq_true (List.all_eq_true.mp checked cell member)',
             '  obtain ⟨size, refApart, entryApart⟩ := facts',
             '  rintro (written | written)',
             f'  · exact InRange.offset_disjoint a cell.1 cell.2 {peer_count} 4',
             '      (by omega) (by decide) refApart _ ⟨i, hi, rfl⟩ written',
             f'  · exact InRange.offset_disjoint a cell.1 cell.2 {entry_peer} 8',
             '      (by omega) (by decide) entryApart _ ⟨i, hi, rfl⟩ written', '',
             'theorem PeerStableFields.mutable_frame {before after : Mem 64}',
             '    {a : BitVec 64} {p : Leanux.WG.Peer}',
             '    (same : EqualOutside (fun address =>',
             '      InRange (a + .ofNat 64 Layouts.peer_refcount) 4 address ∨',
             '      InRange (a + .ofNat 64 peerHandshakePeerOffset) 8 address) before after)',
             '    (represented : PeerStableFields before a p) : PeerStableFields after a p :=',
             '  represented.frame same (peerStable_mutable_disjoint a)', '',
             '#print axioms peerStable_mutable_disjoint', '#print axioms PeerStableFields.mutable_frame',
             'end Binary', '']
    (root / 'binary/PeerScalars.lean').write_text('\n'.join(text))
